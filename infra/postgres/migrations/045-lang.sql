-- Язык человека и язык организации.
--
-- Выбор языка жил только в браузере: интерфейс переключался, а письмо
-- написать было не на чем — мы попросту не знали, на каком языке с
-- человеком говорить, когда его нет на экране. Письмо о конце срока на
-- чужом языке читается как спам.
--
-- Два поля, а не одно. Язык человека — его личный выбор, он и правит
-- его переключателем. Язык организации нужен письмам «в компанию», где
-- получателей несколько и общего выбора нет; он же достаётся новым
-- людям до того, как они что-нибудь переключат.
ALTER TABLE users
  ADD COLUMN IF NOT EXISTS lang text NOT NULL DEFAULT '';

ALTER TABLE tenants
  ADD COLUMN IF NOT EXISTS lang text NOT NULL DEFAULT 'uk';
