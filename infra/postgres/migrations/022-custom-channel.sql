-- Миграция 022 — свой канал.
--
-- Канал без платформы: на той стороне не Meta и не Telegram, а код
-- клиента. Он присылает нам входящие и принимает исходящие — и этого
-- достаточно, чтобы переписка жила в общей ленте наравне с остальными.
--
-- Появился он не от любви к обобщениям, а из упрямого случая. У клиента
-- уже работает самописный бот Telegram со своими сценариями, и забрать
-- у него вебхук нельзя: токен допускает ровно один, второй затрёт
-- первый и сценарии умрут. Делать ради этого «Telegram, но чужой» —
-- значит потом делать то же для Viber, потом для SMS-шлюза, потом для
-- формы на сайте. Вместо очереди частных случаев один канал, где
-- платформа — забота клиента, а наше дело принять и отдать.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE channels DROP CONSTRAINT IF EXISTS channels_type_check;
ALTER TABLE channels ADD CONSTRAINT channels_type_check
  CHECK (type IN ('whatsapp','instagram','messenger',
                  'telegram_bot','telegram_business','telegram_user',
                  'viber_business','webchat','custom'));

COMMIT;
