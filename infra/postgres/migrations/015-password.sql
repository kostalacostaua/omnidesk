-- Миграция 015 — вход по паролю рядом с кодом на почту.
--
-- Код на почту остаётся основным способом: он ничего не требует от
-- человека и заодно подтверждает, что ящик его. Но у оператора,
-- который заходит в смену каждое утро, письмо на каждый вход — это
-- лишняя минута и зависимость от почтового ящика, который может
-- лежать. Поэтому пароль — второй способ, по желанию.
--
-- Хранится не пароль, а его проверочная строка: scrypt с солью,
-- параметры записаны рядом со значением. Понадобится усилить — старые
-- строки продолжат проверяться своими параметрами, а новые получат
-- новые. Без этого смена параметров означала бы «всем сбросить пароль».
--
-- Идемпотентна.

BEGIN;

ALTER TABLE users ADD COLUMN IF NOT EXISTS password_hash text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS password_set_at timestamptz;

COMMENT ON COLUMN users.password_hash IS
  'scrypt: scrypt$N$r$p$соль$хэш в base64url. Пароль не хранится.';

COMMIT;
