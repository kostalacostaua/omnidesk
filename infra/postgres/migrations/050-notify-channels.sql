-- Миграция 050 — оповещения по каналам, а не только по событиям.
--
-- Адресат подписывался на событие, и «нове повідомлення» приходило из
-- всех каналов сразу. Так устроена одна компания из двух: у второй
-- витрина в Instagram и оптовый отдел в Telegram, и дежурному по
-- витрине сообщения оптовиков не нужны — он их не читает, а через
-- неделю перестаёт читать и свои.
--
-- Пусто здесь означает «всі канали», и это отличается от events, где
-- пусто означает «нічого не присилати». Разница не прихоть: события
-- выбирают осознанно, а каналы у большинства компаний не выбирают
-- вовсе — и адресат, созданный до этой миграции, обязан продолжать
-- работать ровно так же, как работал.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE notify_targets
  ADD COLUMN IF NOT EXISTS channels uuid[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN notify_targets.channels IS
  'Каналы, о которых оповещаем. Пусто — обо всех.';

COMMIT;
