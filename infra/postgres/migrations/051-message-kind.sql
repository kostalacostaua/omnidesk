-- Миграция 051 — заметка для команды.
--
-- Оператору нужно оставить в переписке строку, которую клиент не
-- увидит: «обіцяв знижку 10%», «дзвонив, не бере», «це той самий, що
-- повертав у серпні». Сейчас такое пишут в мессенджер коллеге — и
-- через неделю этого нет нигде, а тот, кто возьмёт диалог следующим,
-- начинает с нуля.
--
-- Заметка живёт в messages, а не в отдельной таблице: она стоит в
-- ленте между сообщениями, читается вместе с ними и имеет смысл
-- только на своём месте во времени. Отдельная таблица означала бы
-- слияние двух лент при каждом открытии диалога.
--
-- Различает их kind. Это признак, а не статус: статус говорит, что
-- стало с отправкой, а заметку никто не отправляет — и путь отправки
-- её не видит вовсе. Отсюда и защита: заметка не может «случайно
-- уйти клиенту», потому что в очередь её никто не кладёт.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE messages
  ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'message';

COMMENT ON COLUMN messages.kind IS
  'message — переписка с клиентом; note — заметка для команды, наружу не уходит.';

-- NOT VALID, потом VALIDATE: проверка существующих строк идёт под
-- слабой блокировкой и не держит запись в таблицу, а новые строки
-- проверяются с первой же секунды.
ALTER TABLE messages DROP CONSTRAINT IF EXISTS messages_kind_chk;
ALTER TABLE messages
  ADD CONSTRAINT messages_kind_chk CHECK (kind IN ('message','note')) NOT VALID;
ALTER TABLE messages VALIDATE CONSTRAINT messages_kind_chk;

COMMIT;
