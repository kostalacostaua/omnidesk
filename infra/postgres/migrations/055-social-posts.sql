-- Миграция 055 — пост, под которым идёт разговор.
--
-- Комментарий без поста — это реплика без вопроса. Оператор видит
-- «а дешевле бывает?» и не знает, о чём речь: о доставке, о конкретном
-- товаре или о вчерашней акции. Он идёт в Facebook, ищет пост глазами,
-- возвращается — и так на каждый комментарий. Ссылка «під постом» у нас
-- была и раньше, но ссылка уводит из кабинета, а вопрос стоит здесь.
--
-- Хранить пост отдельной таблицей, а не полем в сообщении, нужно по
-- двум причинам, и обе дорогие.
--
-- Первая: под одним постом пишут десятки людей, и у каждого свой
-- диалог. Текст поста в каждом сообщении — это тот же текст, записанный
-- столько раз, сколько пришло комментариев, и переписанный заново при
-- каждом редактировании поста.
--
-- Вторая: за текстом надо идти в Graph API, а комментарии под вирусным
-- постом приходят пачками по сотне. Один запрос на пост против одного
-- на комментарий — это разница между «работает» и «отказ по лимитам
-- ровно тогда, когда комментариев много». Таблица и есть то место, где
-- видно, что пост уже забран.
--
-- Поэтому ключ — (компания, канал, пост): один и тот же пост в разных
-- подключениях Facebook и Instagram живёт отдельно, потому что и текст
-- забирается разными маркерами.
--
-- Идемпотентна.

BEGIN;

CREATE TABLE IF NOT EXISTS social_posts (
  tenant_id  uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  channel_id uuid NOT NULL REFERENCES channels(id) ON DELETE CASCADE,
  -- Идентификатор поста у Meta: составной у Facebook (страница_пост),
  -- обычный у Instagram.
  post_id    text NOT NULL,
  -- Текст поста. Пусто — пост из одной картинки, и это не ошибка:
  -- комментируют и такое.
  text       text,
  -- Адрес записи. Берём от Meta, а не собираем сами: у Instagram
  -- собрать его из идентификатора нельзя вовсе.
  permalink  text,
  picture    text,
  posted_at  timestamptz,
  -- Когда ходили за текстом. Нужно не для порядка: пост правят, и
  -- однажды мы захотим перечитать старые.
  fetched_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, channel_id, post_id)
);

SELECT apply_tenant_rls('social_posts');

COMMIT;
