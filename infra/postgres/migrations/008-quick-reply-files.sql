-- Миграция 008 — вложения к шаблонам ответов.
--
-- Оператор чаще всего отправляет не текст, а одно и то же вместе с ним:
-- прайс в pdf, схему проезда картинкой, инструкцию. Без вложения шаблон
-- экономит половину работы, а вторую половину человек каждый раз делает
-- руками — ищет файл на диске.
--
-- Хранится только описание: ключ в хранилище, тип, имя и размер. Сам
-- файл лежит там же, где вложения переписки, и отдаётся тем же способом.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE quick_replies
  ADD COLUMN IF NOT EXISTS attachments jsonb NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN quick_replies.attachments IS
  'Массив описаний файлов: storageKey, mime, filename, size, type. '
  'Сами файлы — в хранилище вложений.';

COMMIT;
