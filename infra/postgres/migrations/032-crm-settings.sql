-- Миграция 032 — что заводить в CRM и на кого записывать.
--
-- До сих пор на нового человека всегда заводился лид. Отделу продаж это
-- верно: лид проходит квалификацию и становится сделкой. Но там, где
-- пишут уже купившие, лид — лишний шаг, после которого карточку всё
-- равно конвертируют руками.
--
-- Второе поле про ответственного. «Взял чат — стал ответственным и в
-- CRM» руками делается через раз, а потом никто не понимает, почему в
-- отчёте продаж половина карточек висит на владельце.
--
-- Пусто означает прежнее поведение: лид и без назначения. Менять
-- поведение молча у тех, кто уже работает, нельзя.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE tenants
  ADD COLUMN IF NOT EXISTS crm jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN tenants.crm IS
  'Поведение связки с CRM: {createAs: lead|contact, ownerByEmail}. Пусто — лид без назначения.';

COMMIT;
