-- Срок пробного периода.
--
-- Пробный период был обещанием без даты: организация заводилась без
-- «оплачено до», и кончиться он не мог. Продать после такого нечего —
-- человеку и так всё работает, а мы не знаем, кому пора напомнить.
--
-- Тем, кто уже внутри, ставим четырнадцать дней от сегодня, а не от дня
-- регистрации. Задним числом отключить того, кто вчера работал, — это
-- не «включили правило», это сломали человеку день.
UPDATE tenants
   SET paid_until = current_date + 14
 WHERE paid_until IS NULL
   AND kind <> 'partner'
   AND status <> 'deleted';
