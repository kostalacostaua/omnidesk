-- Миграция 037 — партнёрский кабинет.
--
-- Не всякая организация в списке — клиент. Часть кабинетов партнёрские:
-- их держат те, кто приводит клиентов и работает в сервисе сам. Денег с
-- них не берут, счетов не выставляют, и «не оплачено» напротив такого
-- кабинета — не сигнал, а шум, из-за которого перестают замечать
-- настоящие долги.
--
-- Отдельная колонка, а не значение в «оплачено до» на сто лет вперёд:
-- партнёрство — это не оплаченный период, и запись «оплачено до 2125
-- года» однажды прочитают буквально.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE tenants ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'client';

ALTER TABLE tenants DROP CONSTRAINT IF EXISTS tenants_kind_check;
ALTER TABLE tenants ADD CONSTRAINT tenants_kind_check
  CHECK (kind IN ('client','partner'));

-- Прайс: цена тарифа в каждой валюте.
--
-- Лежит рядом с реквизитами, потому что это тоже настройка продавца, а
-- не свойство клиента. Без неё цену вписывают руками на каждом
-- кабинете, и через месяц у трёх клиентов на одном тарифе три разные
-- цены, про которые никто не помнит, откуда они взялись.
ALTER TABLE platform_settings
  ADD COLUMN IF NOT EXISTS plan_prices jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMIT;
