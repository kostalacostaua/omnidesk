-- Миграция 029 — отметки о разовых переносах данных.
--
-- Лента событий появилась вчера, а переписка — полгода назад. Отчёт,
-- который начинается с пустого места и молчит про всё, что было до
-- вчера, человек читает как «сервис ничего не считает».
--
-- Поэтому события из старых сообщений восстанавливаются один раз. Но
-- «один раз» надо где-то запомнить: api перезапускается при каждой
-- выкатке, и без отметки перенос шёл бы заново после каждой.
--
-- Отдельная таблица, а не строка в _migrations: перенос — не изменение
-- схемы, он идёт долго, под приложением, и повторить его руками должно
-- быть можно, просто удалив отсюда строку.
--
-- Идемпотентна.

BEGIN;

CREATE TABLE IF NOT EXISTS backfills (
  name     text PRIMARY KEY,
  done_at  timestamptz NOT NULL DEFAULT now(),
  note     text
);

GRANT SELECT, INSERT, UPDATE ON backfills TO app_user;

COMMIT;
