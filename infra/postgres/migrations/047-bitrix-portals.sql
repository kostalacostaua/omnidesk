-- Миграция 047 — чей портал Битрикса постучался.
--
-- Битрикс приходит к нам сам: при установке приложения и при каждом
-- открытии виджета он шлёт запрос на адрес, который клиент вписал в
-- карточку приложения. В этом запросе есть опознаватель портала и нет
-- ничего про нашу компанию — а знать её надо до того, как мы сможем
-- выставить контекст изоляции. Та же задача, что у channel_routes, и
-- то же решение: маленькая таблица без данных клиентов.
--
-- Ключ установки живёт в адресе обработчика и создаётся до установки:
-- в момент, когда человек только копирует адрес к себе в Битрикс, про
-- портал не известно ещё ничего. Опознаватель портала появляется
-- позже, при первом запросе оттуда.
--
-- Внутри только идентификаторы: ни токенов, ни переписки. Токены лежат
-- в crm_connections, зашифрованные ключом арендатора.
--
-- Идемпотентна.

BEGIN;

CREATE TABLE IF NOT EXISTS bitrix_portals (
  -- Он же хвост адреса обработчика.
  install_key text PRIMARY KEY,
  tenant_id   uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  -- Опознаватель портала: у Битрикса он не меняется при переименовании
  -- и переезде, в отличие от адреса.
  member_id   text UNIQUE,
  domain      text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  linked_at   timestamptz
);

CREATE INDEX IF NOT EXISTS bitrix_portals_tenant_idx ON bitrix_portals (tenant_id);

GRANT SELECT, INSERT, UPDATE, DELETE ON bitrix_portals TO app_user;

COMMENT ON TABLE bitrix_portals IS
  'Ключ установки и опознаватель портала Битрикса → компания. Нужна до определения тенанта, поэтому без RLS. Секретов не содержит.';

COMMIT;
