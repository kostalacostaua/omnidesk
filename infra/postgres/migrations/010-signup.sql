-- Миграция 010 — самостоятельная регистрация.
--
-- До сих пор код на почту уходил только тому, кто уже заведён в базе.
-- Это было сделано осознанно — чтобы форма входа не превращалась в
-- справочник сотрудников, — но означало, что новая компания не может
-- начать пользоваться сервисом без нас.
--
-- Теперь у кода есть намерение: вход или регистрация. Название компании
-- хранится рядом с кодом и превращается в тенанта ровно в тот момент,
-- когда человек подтвердил, что владеет почтой. До подтверждения в базе
-- нет ни тенанта, ни пользователя — иначе перебором адресов можно было
-- бы засорить базу пустыми организациями.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE auth_codes
  ADD COLUMN IF NOT EXISTS is_signup boolean NOT NULL DEFAULT false;
ALTER TABLE auth_codes
  ADD COLUMN IF NOT EXISTS signup_company text;

COMMENT ON COLUMN auth_codes.is_signup IS
  'Код выдан для регистрации новой компании, а не для входа.';

-- Пометка «откуда пришёл» у тенанта: заявка с промо, самостоятельная
-- регистрация или заведён нами вручную. Нужна для одного вопроса,
-- который возникает на второй неделе: откуда вообще берутся клиенты.
ALTER TABLE tenants
  ADD COLUMN IF NOT EXISTS source text NOT NULL DEFAULT 'manual';

COMMIT;
