-- Миграция 019 — собственный бот у адресата оповещений.
--
-- Адресат в Telegram умел ссылаться только на уже подключённый канал.
-- Для тех, у кого канал-бот есть, это правильно: второй экземпляр
-- токена — это второе место, откуда он может утечь.
--
-- Но у большинства бота-канала нет и не будет: клиенты пишут в
-- Instagram и на номер, а для дежурной группы нужен отдельный бот,
-- который клиентам не показывают вовсе. Раньше такой человек открывал
-- раздел и видел «спочатку підключіть Telegram-бота» — то есть
-- предложение завести лишний канал ради оповещений.
--
-- Теперь у адресата может быть свой токен. Он лежит зашифрованным
-- ключом компании, ровно как токен канала, и наружу не возвращается
-- никогда: в интерфейсе видно имя бота, а не ключ.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE notify_targets
  ADD COLUMN IF NOT EXISTS credentials_enc bytea;

COMMENT ON COLUMN notify_targets.credentials_enc IS
  'Токен собственного бота адресата, зашифрован ключом тенанта. '
  'Пусто — берём токен подключённого канала по config.channelId.';

COMMIT;
