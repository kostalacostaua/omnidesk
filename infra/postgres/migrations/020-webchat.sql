-- Миграция 020 — чат на сайте.
--
-- Последний канал, где клиент ещё не может написать: он стоит на сайте
-- и не хочет открывать мессенджер. Виджет закрывает именно это — и
-- заодно превращает анонимного посетителя в диалог, который дальше
-- живёт по общим правилам: сценарии, ИИ, оповещения, CRM.
--
-- Отдельной таблицы посетителей нет намеренно. Посетитель — такой же
-- контакт, как человек из Instagram: он опознаётся строкой в
-- contact_identities с типом канала webchat. Иначе у нас появился бы
-- второй сорт собеседников, и каждую возможность пришлось бы писать
-- дважды.
--
-- Ключ сайта лежит в external_id канала. Он публичный: его видно в коде
-- страницы у каждого посетителя, и секретом он не является — по нему
-- можно только начать разговор, но не прочитать чужой.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE channels DROP CONSTRAINT IF EXISTS channels_type_check;
ALTER TABLE channels ADD CONSTRAINT channels_type_check
  CHECK (type IN ('whatsapp','instagram','messenger',
                  'telegram_bot','telegram_business','telegram_user',
                  'viber_business','webchat'));

COMMIT;
