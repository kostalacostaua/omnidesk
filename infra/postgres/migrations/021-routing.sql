-- Миграция 021 — очередь обработки канала.
--
-- Доступ к каналу («кто его видит») уже есть: user_channels. Но видеть
-- диалог и отвечать на него — разные вещи. Когда операторов больше
-- одного, новый диалог висит ничьим: каждый думает, что его возьмёт
-- другой, и клиент ждёт дольше всех.
--
-- Отсюда правило распределения у канала:
--
--   none        — никому, как было: берут руками;
--   round_robin — по кругу между теми, кому канал виден;
--   user        — всегда одному человеку.
--
-- Состояние круга живёт здесь же, в поле lastUserId: отдельная таблица
-- ради одной строки на канал — это лишний JOIN в горячем пути и лишний
-- повод для рассинхрона.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE channels
  ADD COLUMN IF NOT EXISTS routing jsonb NOT NULL DEFAULT '{"mode":"none"}'::jsonb;

COMMENT ON COLUMN channels.routing IS
  'Распределение новых диалогов: {mode: none|round_robin|user, userId, lastUserId}.';

COMMIT;
