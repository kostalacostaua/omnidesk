-- Миграция 030 — обещание по времени ответа.
--
-- SLA здесь — не таблица правил на каждый случай, а два числа: за
-- сколько мы обещаем ответить и за сколько закрыть. Это намеренно.
-- Правила «в рабочее время двадцать минут, ночью два часа, для опта
-- десять» выглядят точнее, но человек их не настраивает: он не знает
-- своих чисел, пока не увидит первый отчёт. Два числа он задаёт за
-- минуту и сразу видит, сколько раз их нарушили.
--
-- Считается в рабочих часах — тех же, что и время ответа в отчётах.
-- Обещание «двадцать минут», нарушенное ночью, когда никто не работает,
-- это не нарушение, а неверно поставленный вопрос.
--
-- Пусто — обещания нет: отчёт покажет времена, но ничего не назовёт
-- просрочкой. Молча подставить «полчаса» значило бы объявить чужое
-- обещание от имени компании.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE tenants
  ADD COLUMN IF NOT EXISTS sla jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN tenants.sla IS
  'Обещание: {firstReplyMinutes, resolveMinutes} в рабочих часах. Пусто — нет обещания.';

COMMIT;
