-- Оповещение о каждом сообщении клиента, а не только о первом.
--
-- Адресаты, заведённые раньше, подписаны на события списком, и нового
-- события в этом списке нет. Молча оставить их как есть — значит
-- выкатить возможность, которой ни у кого не будет: человек добавлял
-- адресата, чтобы узнавать о клиентах, а не о первых сообщениях.
--
-- Поэтому добавляем новое событие тем, кто уже подписан на «новый
-- диалог»: это то же намерение, выраженное доступными тогда словами.
-- Кто от «нового диалога» отписался сам — того не трогаем.
UPDATE notify_targets
   SET events = array_append(events, 'message.new')
 WHERE 'conversation.new' = ANY (events)
   AND NOT ('message.new' = ANY (events));
