-- Что именно куплено по счёту.
--
-- Счёт был только суммой: сколько заплатить и за какой период. Пока
-- тариф у организации менял владелец руками, этого хватало. Теперь
-- тариф выбирает сам клиент — и, если тариф корпоративный, выбирает
-- ещё и число лицензий. Оплата такого счёта должна не просто продлить
-- срок, а перевести организацию на купленное; без этих двух полей
-- «что куплено» пришлось бы угадывать по сумме.
ALTER TABLE platform_invoices
  ADD COLUMN IF NOT EXISTS plan  text NOT NULL DEFAULT '',
  -- Пусто у тарифов, где места не покупают поштучно.
  ADD COLUMN IF NOT EXISTS seats integer;
