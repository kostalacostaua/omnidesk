-- Миграция 054 — вернуть комментариям их настоящую дату.
--
-- Instagram присылает entry.time в СЕКУНДАХ, а Date в JavaScript ждёт
-- миллисекунды. Код это уже умеет (eventMillis), но правка не чинит
-- того, что записано до неё: комментарий, принятый раньше, так и стоит
-- в ленте 21 января 1970 года, а его диалог — в самом низу списка,
-- потому что список сортируется по дате последнего сообщения.
--
-- Починить это можно точно, а не на глаз. Ошибка обратима: число
-- секунд записалось как число миллисекунд, значит настоящее время —
-- ровно в тысячу раз больше того, что лежит в базе.
--
-- Берём только то, что заведомо сломано: сообщения каналов
-- комментариев с датой из 1970-го. Настоящий комментарий из 1970 года
-- невозможен, а других каналов эта ошибка не касалась — она жила в
-- разборе вебхука комментариев.
--
-- И проверяем, что получилось: если после умножения вышло не похожее
-- на правду время — раньше, чем существовал продукт, или из будущего,
-- — строку не трогаем вовсе. Неверная дата лучше выдуманной.
--
-- Идемпотентна: повторный запуск не найдёт ни одной строки, потому что
-- починенные уже не лежат в 1970-м.

BEGIN;

UPDATE messages m
   SET sent_at = f.fixed
  FROM (
    SELECT m2.id,
           to_timestamp(extract(epoch FROM m2.sent_at) * 1000) AS fixed
      FROM messages m2
      JOIN channels ch ON ch.id = m2.channel_id
     WHERE ch.type IN ('instagram_comments', 'messenger_comments')
       AND m2.sent_at < timestamptz '1971-06-01'
  ) f
 WHERE m.id = f.id
   AND f.fixed >= timestamptz '2024-01-01'
   AND f.fixed <= now() + interval '1 day';

/*
 * Дата последнего сообщения в диалоге. Она ведёт список чатов, и
 * чинить сообщения, не тронув её, значит оставить диалог внизу списка
 * с правильными датами внутри.
 *
 * Пересчитываем из самих сообщений, а не умножаем: у диалога их может
 * быть несколько, и верная дата — это дата последнего, какой бы она ни
 * была. Трогаем только диалоги, застрявшие в 1970-м.
 */
UPDATE conversations c
   SET last_message_at = s.at
  FROM (
    SELECT conversation_id, max(sent_at) AS at
      FROM messages
     GROUP BY conversation_id
  ) s
 WHERE c.id = s.conversation_id
   AND c.last_message_at < timestamptz '1971-06-01'
   AND s.at IS NOT NULL;

COMMIT;
