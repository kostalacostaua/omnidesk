-- Миграция 025 — папки для шаблонов ответов.
--
-- Шаблонов сначала пять, и список плоский. Потом их сорок: доставка,
-- возвраты, оплата, «приветствия на три случая», — и человек ищет в
-- списке глазами вместо того, чтобы ответить.
--
-- Папка здесь — обычное имя, а не таблица. Причина простая: папка без
-- шаблонов никому не нужна, а таблица заводит ей отдельную жизнь —
-- пустые папки, порядок папок, удаление папки с шаблонами внутри. Имя
-- в колонке всего этого не заводит: папка появляется, когда в неё
-- положили первый шаблон, и исчезает, когда забрали последний.
--
-- Пустая строка вместо NULL: «без папки» — это тоже группа, и в
-- сортировке она обязана вести себя как значение, а не как дырка.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE quick_replies
  ADD COLUMN IF NOT EXISTS folder text NOT NULL DEFAULT '';

COMMENT ON COLUMN quick_replies.folder IS
  'Имя папки. Пусто — шаблон лежит сам по себе, вне папок.';

CREATE INDEX IF NOT EXISTS quick_replies_folder_idx
  ON quick_replies (tenant_id, folder, shortcut);

COMMIT;
