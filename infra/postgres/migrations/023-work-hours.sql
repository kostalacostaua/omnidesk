-- Миграция 023 — рабочие часы организации.
--
-- Нужны трём вещам сразу, и каждая видна человеку:
--
--   оповещения — «клиент ждёт двадцать минут» в три ночи будит хозяина
--   ради того, на что всё равно никто не ответит;
--
--   чат на сайте — молча принятое в воскресенье сообщение обещает
--   ответ, которого не будет до понедельника;
--
--   счёт времени ответа — без рабочих часов «ответили через
--   четырнадцать часов» складывается из ночи и не говорит ни о чём.
--
-- По умолчанию круглосуточно. Не потому, что так работают, а потому
-- что таково поведение до настройки: пока человек не сказал иное, мы не
-- имеем права молчать клиенту и прятать оповещение.
--
-- Идемпотентна.

BEGIN;

ALTER TABLE tenants
  ADD COLUMN IF NOT EXISTS work_hours jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN tenants.work_hours IS
  'Рабочие часы: {tz, days:[{on,allDay,from,to} × 7 с понедельника]}. Пусто — круглосуточно.';

COMMIT;
