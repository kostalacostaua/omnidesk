-- Миграция 052 — снять с клиентов имя владельца номера.
--
-- Номерной WhatsApp присылает в каждом сообщении pushName — имя того,
-- КТО его отправил. В исходящем это владелец номера. Имя контакта
-- ставится один раз, при создании, и чат, который начался ответом с
-- телефона, получал в списке имя владельца. Три разных клиента
-- показывались одним человеком, и открыть нужный можно было наугад.
--
-- Код исправлен: имя берётся только из входящего. Но уже записанные
-- имена исправить может только эта миграция.
--
-- Берём не всех, а тех, у кого имя заведомо чужое: имя контакта в
-- точности равно имени из профиля, запомненного при создании, и самое
-- раннее сообщение в переписке по этому каналу — исходящее. Контакт,
-- заведённый оператором из кабинета, под это не подходит: там в
-- профиле имени нет вовсе.
--
-- Имя снимаем, а не угадываем: в списке вместо него встанет телефон,
-- а настоящее имя придёт с первым входящим сообщением.
--
-- Идемпотентна: повторный запуск не найдёт ни одной строки.

BEGIN;

UPDATE contacts ct
   SET display_name = NULL
 WHERE ct.display_name IS NOT NULL
   AND EXISTS (
     SELECT 1
       FROM contact_identities ci
      WHERE ci.contact_id = ct.id
        AND ci.channel_type = 'whatsapp_user'
        AND ci.raw_profile->>'name' = ct.display_name
   )
   AND (
     SELECT m.direction
       FROM messages m
       JOIN conversations cv ON cv.id = m.conversation_id
       JOIN channels ch ON ch.id = cv.channel_id
      WHERE cv.contact_id = ct.id
        AND ch.type = 'whatsapp_user'
      ORDER BY m.sent_at ASC, m.id ASC
      LIMIT 1
   ) = 'out';

COMMIT;
