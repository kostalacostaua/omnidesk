-- Плата за место сверх тарифа.
--
-- До сих пор в цене была одна цифра — сколько организация платит в
-- месяц. Этого хватало, пока тариф был один на всех. Но у тарифа есть
-- включённые места, а команда растёт: пятнадцать операторов на тарифе с
-- десятью — это не тот же счёт, что десять.
--
-- Два числа вместо одного. Сколько мест входит в тариф и сколько стоит
-- каждое сверх. Оба у организации, а не у тарифа: корпоративный
-- считается индивидуально и по головам — там включённых мест ноль, а
-- цена места и есть вся цена.
ALTER TABLE tenants ADD COLUMN IF NOT EXISTS seats_free int NOT NULL DEFAULT 0;
ALTER TABLE tenants ADD COLUMN IF NOT EXISTS seat_price numeric(10,2) NOT NULL DEFAULT 0;

-- У тех, кто уже есть, все места считаем включёнными: цена им назначена
-- за то число мест, которое стоит сейчас, и внезапно выставить им доплату
-- за существующих людей было бы обманом.
UPDATE tenants SET seats_free = seats_limit WHERE seats_free = 0 AND seat_price = 0;
