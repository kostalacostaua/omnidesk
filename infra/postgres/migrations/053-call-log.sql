-- Миграция 053 — отметка о звонке.
--
-- Половина разговоров кончается словами «наберу вас». Дальше оператор
-- звонит с телефона, и в кабинете от этого не остаётся ничего: тот,
-- кто возьмёт диалог следующим, видит вопрос клиента без ответа и
-- спрашивает то же самое второй раз. А в отчёте такая работа не
-- существует вовсе.
--
-- Голос мы не несём и нести не собираемся: ни WhatsApp, ни Telegram не
-- дают звонить из сессии ничем, что можно поставить в сервис людям.
-- Но сам факт звонка — наш, и он стоит ровно там, где случился: в
-- ленте, между вопросом и ответом.
--
-- Поэтому новый вид сообщения, а не таблица звонков: отметка читается
-- вместе с перепиской и имеет смысл только на своём месте во времени.
-- Отдельная таблица означала бы слияние двух лент при каждом открытии.
--
-- Клиенту не уходит по той же причине, что и заметка: в очередь
-- отправки её никто не кладёт.
--
-- Идемпотентна.

BEGIN;

COMMENT ON COLUMN messages.kind IS
  'message — переписка с клиентом; note — заметка для команды; call — отметка о звонке. Наружу уходит только message.';

ALTER TABLE messages DROP CONSTRAINT IF EXISTS messages_kind_chk;
ALTER TABLE messages
  ADD CONSTRAINT messages_kind_chk CHECK (kind IN ('message','note','call')) NOT VALID;
ALTER TABLE messages VALIDATE CONSTRAINT messages_kind_chk;

COMMIT;
