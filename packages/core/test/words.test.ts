import { describe, expect, it } from 'vitest';
import { moneyWords, numberWords, plural } from '../src/words.js';

/*
 * Сумма прописью — защита от дописанной цифры и первое, что сверяет
 * бухгалтер. Ошибка здесь не видна на глаз в коде, зато прекрасно
 * видна в чужой бухгалтерии, поэтому проверяем числительные по всем
 * местам, где они меняют форму.
 */
describe('число словами', () => {
  it('единицы, десятки и сотни', () => {
    expect(numberWords(1)).toBe('один');
    expect(numberWords(11)).toBe('одинадцять');
    expect(numberWords(21)).toBe('двадцять один');
    expect(numberWords(40)).toBe('сорок');
    expect(numberWords(100)).toBe('сто');
    expect(numberWords(268)).toBe('двісті шістдесят вісім');
  });

  // Тысячи женского рода: «одна тисяча», а не «один тисяча».
  it('тысячи стоят в женском роде', () => {
    expect(numberWords(1000)).toBe('одна тисяча');
    expect(numberWords(2000)).toBe('дві тисячі');
    expect(numberWords(5000)).toBe("п'ять тисяч");
    expect(numberWords(68_040)).toBe('шістдесят вісім тисяч сорок');
  });

  it('ноль называется словом, а не пустотой', () => {
    expect(numberWords(0)).toBe('нуль');
  });

  // Одиннадцать — не «одна», а «одинадцять»: на этом ломаются почти
  // все самодельные склонения.
  it('одиннадцать и двенадцать берут форму «много»', () => {
    expect(plural(11, 'гривня', 'гривні', 'гривень')).toBe('гривень');
    expect(plural(12, 'гривня', 'гривні', 'гривень')).toBe('гривень');
    expect(plural(21, 'гривня', 'гривні', 'гривень')).toBe('гривня');
    expect(plural(22, 'гривня', 'гривні', 'гривень')).toBe('гривні');
    expect(plural(25, 'гривня', 'гривні', 'гривень')).toBe('гривень');
  });
});

describe('сумма прописью', () => {
  it('пишется так же, как в бумажном счёте', () => {
    expect(moneyWords('68040.00')).toBe('шістдесят вісім тисяч сорок гривень 00 копійок');
    expect(moneyWords(1)).toBe('одна гривня 00 копійок');
    expect(moneyWords(2.5)).toBe('дві гривні 50 копійок');
    expect(moneyWords(21.01)).toBe('двадцять одна гривня 01 копійка');
  });

  // Копейки считаются через целые: 0.1 + 0.2 в двоичной дроби не даёт
  // 0.3, и на сумме счёта это однажды становится видно.
  it('копейки не теряются на дробях', () => {
    expect(moneyWords(1200.1)).toContain('10 копійок');
    expect(moneyWords('19,90')).toBe("дев'ятнадцять гривень 90 копійок");
  });

  it('валюту называет своим словом', () => {
    expect(moneyWords(2, 'USD')).toBe('два долари 00 центів');
    expect(moneyWords(5, 'EUR')).toBe("п'ять євро 00 центів");
    // Незнакомая валюта — гривня: счёт по безналу у нас в ней одной.
    expect(moneyWords(5, 'PLN')).toContain('гривень');
  });
});
