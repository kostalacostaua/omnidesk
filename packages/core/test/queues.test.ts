import { describe, expect, it } from 'vitest';
import { jobKey } from '../src/queues.js';

/**
 * Эти проверки написаны по следам конкретной аварии.
 *
 * Задачи на скачивание вложений создавались с идентификатором вида
 * «messageId:0». BullMQ такие отклоняет — двоеточие у него служебное.
 * Ошибка при этом не всплывала наверх заметным образом: сообщение
 * сохранялось, оператор видел «вложение загружается», и оно висело так
 * вечно. Ни одного признака поломки, кроме одной строки в логе воркера.
 *
 * Отдельно коварно то, что проверка BullMQ пропускает строку ровно
 * из трёх частей — историческое исключение для повторяющихся задач.
 * Поэтому «react:id:emoji» работал, а «messageId:0» — нет, и поломка
 * выглядела выборочной.
 */
describe('jobKey', () => {
  it('собирает ключ через двойной дефис', () => {
    expect(jobKey('abc', 0)).toBe('abc--0');
    expect(jobKey('react', 'id-1', 'none')).toBe('react--id-1--none');
  });

  it('никогда не возвращает строку с двоеточием', () => {
    expect(jobKey('a', 'b', 'c')).not.toContain(':');
    expect(jobKey('msg', 1, 'retry', 1700000000000)).not.toContain(':');
  });

  it('падает, если двоеточие пришло внутри части', () => {
    // Именно этот случай и был в бою: идентификатор сообщения Telegram
    // имеет вид «chatId:messageId», и попадание его в ключ задачи
    // ломало очередь молча.
    expect(() => jobKey('455273305:11', 0)).toThrow(/двоеточие/);
  });

  it('устойчив к числам и нулю', () => {
    expect(jobKey(0)).toBe('0');
    expect(jobKey('x', 0, 1)).toBe('x--0--1');
  });

  /**
   * Проверка правила самого BullMQ, воспроизведённая здесь дословно.
   * Если в новой версии оно изменится, тест останется документацией
   * того, почему ключи собираются именно так.
   */
  it('повторяет правило BullMQ: двоеточие проходит только при трёх частях', () => {
    const allowedByBullmq = (id: string) => !id.includes(':') || id.split(':').length === 3;

    expect(allowedByBullmq('uuid:0')).toBe(false); // так было — не работало
    expect(allowedByBullmq('react:id:emoji')).toBe(true); // так было — работало
    expect(allowedByBullmq('uuid:0:retry:123')).toBe(false); // так было — не работало
    expect(allowedByBullmq(jobKey('uuid', 0))).toBe(true); // так стало
  });
});
