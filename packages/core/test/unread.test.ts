import { describe, expect, it } from 'vitest';
import { unreadMove } from '../src/index.js';

/**
 * Счётчик непрочитанного решает, ждёт ли переписка человека: от него
 * жирное имя в списке, цифра на значке и отметка «чекає 5 год».
 *
 * Ошибка здесь не падает, а тихо врёт. Поэтому проверяется не то, что
 * функция что-то возвращает, а каждый из трёх случаев по отдельности —
 * особенно тот, из-за которого всё и чинилось.
 */

describe('что считается прочтением', () => {
  it('клиент написал — переписка ждёт ответа', () => {
    expect(unreadMove('in', 'customer')).toBe('add');
  });

  /*
   * Тот самый случай. Оператор отвечает клиенту прямо из Telegram или
   * WhatsApp, с телефона, не открывая кабинет. Сообщение доходит до нас
   * эхом и ложится в ленту — а диалог оставался непрочитанным, потому
   * что счётчик только «не увеличивали», но не обнуляли. В списке
   * висели жирные имена и «чекає 5 год» у переписок, на которые
   * ответили час назад.
   */
  it('человек ответил — значит, прочитал, даже если отвечал мимо кабинета', () => {
    expect(unreadMove('out', 'agent')).toBe('clear');
  });

  /*
   * Автоответ — не прочтение. Обнули здесь — и диалоги, которые бот не
   * закрыл, пропадут из виду: имя перестанет быть жирным, а человек их
   * так и не увидит.
   */
  it('бот ответил — счётчик не трогаем', () => {
    expect(unreadMove('out', 'bot')).toBe('keep');
  });

  it('системная запись тоже ничего не читает', () => {
    expect(unreadMove('out', 'system')).toBe('keep');
  });

  /*
   * Входящее остаётся входящим, кто бы его ни прислал: правило смотрит
   * на направление первым, иначе сообщение от бота клиента (а такие
   * бывают) считалось бы нашим ответом.
   */
  it('направление решает раньше отправителя', () => {
    for (const who of ['customer', 'agent', 'bot', 'system'] as const) {
      expect(unreadMove('in', who), who).toBe('add');
    }
  });
});
