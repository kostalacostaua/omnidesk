/**
 * Тело ответа Zoho.
 *
 * У Zoho 204 — обычный ответ, а не сбой: «полей нет», «воронка без
 * этапов», «таких товаров уже нет», «ничего не найдено». Тела у такого
 * ответа нет вовсе.
 *
 * Разобрать его как JSON нельзя: JSON.parse на пустой строке бросает
 * «Unexpected end of JSON input». А дальше хуже — ошибка вылетает из
 * обработчика, и человек вместо пустого списка получает 500. Именно
 * так и падала разметка заказа у компании, где у макета сделок не
 * оказалось воронок.
 *
 * Отдельные проверки на 204 по месту уже стояли в половине вызовов —
 * ровно в тех, где однажды об это споткнулись. Остальные ждали своей
 * очереди. Поэтому разбор тела здесь один на все запросы к Zoho, и
 * пустой ответ в нём — обычное дело, а не исключение.
 *
 * Непонятное тело при успешном коде тоже даёт пустой объект: в этом
 * месте разница между «Zoho ответила чепухой» и «Zoho ответила
 * пусто» для вызывающего никакая — ни полей, ни воронок он не получит.
 * А решать, сбой это или нет, ему всё равно по коду ответа, а не по
 * телу.
 */
export async function zohoBody(res: Response): Promise<unknown> {
  if (res.status === 204) return {};
  const text = await res.text().catch(() => '');
  if (!text.trim()) return {};
  try {
    return JSON.parse(text) as unknown;
  } catch {
    return {};
  }
}
