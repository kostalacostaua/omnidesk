/**
 * Непрочитанное.
 *
 * Счётчик у диалога отвечает на один вопрос: ждёт ли эта переписка
 * человека. От него зависит и жирное имя в списке, и цифра на значке,
 * и отметка «чекає 5 год». Поэтому важно не «увеличить или нет», а три
 * отдельных случая — их тут и видно.
 *
 * Правило живёт отдельной функцией, а не внутри запроса, по одной
 * причине: запрос нельзя проверить, не подняв базу, а правило можно.
 * И ошибка здесь не падает, а тихо врёт — список показывает ожидание
 * там, где давно ответили.
 */

import type { Direction, SenderType } from './types.js';

/** Что сделать со счётчиком непрочитанного. */
export type UnreadMove = 'add' | 'clear' | 'keep';

/**
 * Пришло сообщение — что станет со счётчиком.
 *
 *   add    клиент написал: ждём ответа, плюс один.
 *
 *   clear  ответил живой человек. Это и значит «прочитано»: не
 *          ответишь, не прочитав. Сюда попадает ответ, написанный
 *          мимо кабинета — прямо из Telegram или WhatsApp с
 *          телефона. Такое сообщение доходит до нас эхом, и до сих
 *          пор диалог оставался непрочитанным: его никто не
 *          обнулял.
 *
 *   keep   ответил бот или система. Человек этой переписки не видел,
 *          и автоответ не читал её за него. Обнулить здесь значило бы
 *          прятать от оператора диалоги, которые бот не закрыл.
 */
export function unreadMove(direction: Direction, senderType: SenderType): UnreadMove {
  if (direction === 'in') return 'add';
  return senderType === 'agent' ? 'clear' : 'keep';
}
